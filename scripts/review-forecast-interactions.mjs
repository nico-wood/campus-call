import { chromium } from '@playwright/test';
import { createServer } from 'vite';
import { mkdir, writeFile } from 'node:fs/promises';

const output = 'outputs/forecast-detail';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
let preview;
const checks = [];
try {
  for (const width of [1280, 768, 390, 375, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 844 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    let posts = 0;
    page.on('request', request => { if (request.method() === 'POST') posts++; });
    await page.goto('http://127.0.0.1:3000/examples/sports-exhibition-winner');
    await page.getByRole('button', { name: 'Confirm', exact: true }).waitFor();
    await page.evaluate(() => document.fonts.ready);
    if (await page.locator('#example-confirm-note').isVisible()) throw new Error('Example warning appears before confirm');
    if (await page.getByRole('heading', { name: 'Sign in to continue' }).count()) throw new Error('Sign in appears before confirm');
    await page.locator('.market-outcome-row').filter({ hasText: 'No' }).click();
    if (await page.locator('.position-selection strong').textContent() !== 'No') throw new Error('Outcome selection not synchronized');
    await page.locator('.position-choices button').filter({ hasText: 'Yes' }).click();
    if (await page.locator('.market-outcome-row').first().getAttribute('aria-pressed') !== 'true') throw new Error('Ticket selection not synchronized');
    await page.getByRole('button', { name: '100', exact: true }).click();
    if (await page.locator('#position-amount').inputValue() !== '100') throw new Error('Quick amount failed');
    const chart = page.getByRole('slider', { name: 'Explore illustrative probability history' });
    await chart.focus();
    await chart.press('Home');
    if ((await chart.getAttribute('aria-valuetext'))?.includes('62%')) throw new Error('Chart exploration did not change readout');
    await chart.press('End');
    await page.getByRole('button', { name: 'Recent', exact: true }).click();
    await page.getByRole('button', { name: 'Full view', exact: true }).click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: `${output}/detail-${width}.png`, fullPage: true });
    await page.getByRole('button', { name: 'Confirm', exact: true }).click();
    await page.getByRole('heading', { name: 'Sign in to continue' }).waitFor();
    if (!await page.locator('#example-confirm-note').isVisible()) throw new Error('Missing warning after confirm');
    if (posts !== 0) throw new Error('Example confirm sent a request');
    await page.screenshot({ path: `${output}/signin-${width}.png`, fullPage: true });
    await page.goto('http://127.0.0.1:3000/');
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('heading', { name: 'Account & preferences' }).waitFor();
    await page.screenshot({ path: `${output}/settings-${width}.png` });
    await page.keyboard.press('Escape');
    if (await page.getByRole('button', { name: 'Settings', exact: true }).getAttribute('aria-expanded') !== 'false') throw new Error('Settings Escape failed');
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.locator('.workspace-footer p').click();
    if (await page.getByRole('button', { name: 'Settings', exact: true }).getAttribute('aria-expanded') !== 'false') throw new Error('Settings outside click failed');
    await page.goto('http://127.0.0.1:3000/hackathon?section=forecast');
    await page.getByRole('combobox', { name: 'First place', exact: true }).fill('FSH');
    await page.getByRole('combobox', { name: 'First place', exact: true }).press('Enter');
    if (await page.getByRole('combobox', { name: 'First place', exact: true }).inputValue() !== 'FSH') throw new Error('Team selection failed');
    await page.getByRole('combobox', { name: 'Second place', exact: true }).fill('Mission');
    await page.getByRole('option', { name: /Mission Impromptable/ }).click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: `${output}/teams-${width}.png`, fullPage: true });
    const mainTicket = page.locator('[data-ticket="main"]');
    await page.getByRole('combobox', { name: 'Third place', exact: true }).fill('FSH');
    await mainTicket.getByLabel('Virtual credits', { exact: true }).fill('10');
    await mainTicket.getByRole('button', { name: 'Confirm position', exact: true }).click();
    await mainTicket.getByRole('heading', { name: 'Sign in to continue', exact: true }).waitFor();
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(`Overflow at ${width}`);
    if (errors.length) throw new Error(errors.join('\n'));
    checks.push(`${width}px: synchronized outcomes, quick amounts, keyboard chart, delayed warning/sign-in, no example confirm POST, settings dismissal, keyboard/mouse team selection, hackathon sign-in boundary passed`);
    await page.close();
  }

  // Isolated Vite harness mounts the real loading component; no preview route in the product.
  await writeFile(`${output}/loader.html`, '<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1"></head><body><div id="root"></div><script type="module">import React from "react";import {createRoot} from "react-dom/client";import Loading from "/src/app/loading.tsx";import "/src/app/globals.css";createRoot(document.getElementById("root")).render(React.createElement(Loading));</script></body></html>');
  preview = await createServer({ configFile: false, server: { host: '127.0.0.1', port: 3002, strictPort: true }, esbuild: { jsx: 'automatic' } });
  await preview.listen();
  const page = await browser.newPage({ viewport: { width: 1280, height: 844 } });
  await page.goto('http://127.0.0.1:3002/outputs/forecast-detail/loader.html');
  await page.getByRole('status', { name: 'Loading Campus Call' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1800);
  await page.screenshot({ path: `${output}/logo-burst-desktop.png` });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.screenshot({ path: `${output}/logo-burst-mobile.png` });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForTimeout(100);
  const firstFrame = await page.locator('canvas').evaluate(canvas => canvas.toDataURL());
  await page.waitForTimeout(150);
  const secondFrame = await page.locator('canvas').evaluate(canvas => canvas.toDataURL());
  if (firstFrame !== secondFrame) throw new Error('Logo burst ignores reduced motion');
  checks.push('Real Logo Burst loader rendered at desktop/mobile; reduced-motion canvas stays static');
  await page.goto('http://127.0.0.1:3000/');
  const staticAnimation = await page.locator('.ambient-green').evaluate(el => getComputedStyle(el).animationName);
  if (staticAnimation !== 'none') throw new Error('Ambient reduced-motion failed');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const before = await page.locator('.ambient-green').evaluate(el => getComputedStyle(el).transform);
  await page.waitForTimeout(1000);
  const after = await page.locator('.ambient-green').evaluate(el => getComputedStyle(el).transform);
  if (before === after) throw new Error('Ambient background does not move');
  checks.push('Ambient background moves slowly; reduced-motion disables its animation');
  await writeFile(`${output}/checks.json`, JSON.stringify(checks, null, 2));
  console.log(checks.join('\n'));
} finally {
  await preview?.close();
  await browser.close();
}
